POLICIES = (("D", lambda p, m: DEP),
            ("C", lambda p, m: f"llm{m}"),
            ("R", lambda p, m: f"hybrid{m}"),
            (r"$C_{\leq3}\!\to\!D$", lambda p, m: f"llm{m}" if p <= 3 else DEP),
            (r"$C_{\leq3}\!\to\!R$", lambda p, m: f"llm{m}" if p <= 3 else f"hybrid{m}"))


def policy(A, kind, choose, m):
    """Exact pooled MRR, CLM share and time of a prefix-dependent strategy choice."""
    rr = n = t = invoked = 0
    for p in PREF:
        s = choose(p, m)
        a = A.get(kind, s, p)
        rr += a["reciprocalRankSum"]; n += a["count"]; t += a["timeMs"]
        if not s.startswith("heuristics"):
            invoked += a["count"]
    return ratio(rr, n), ratio(invoked, n, 100), ratio(t, n)


