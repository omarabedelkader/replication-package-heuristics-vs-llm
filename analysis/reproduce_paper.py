def statistics(A, parts, complete, incomplete, manifest):
    """Every number quoted in the paper. Keys of the original analysis-stats.json are kept."""
    st = {}
    for kind in KINDS:
        for s in STRATEGIES:
            t = A.get(kind, s)
            for p in PREF:
                st[f"mrr/{kind}/{s}/{p}"] = round(mrr(A.get(kind, s, p)), 4)
            st[f"mrr/{kind}/{s}/avg"] = round(mrr(t), 4)
            for f in ("top1", "top2", "top3", "top10"):
                st[f"{f}/{kind}/{s}"] = round(pct(t, f), 2)
        dep = A.get(kind, DEP)
        for s, _ in SIZES:
            tb, ta = A.get(kind, f"llmUnvalidated{s}"), A.get(kind, f"llm{s}")
            for k, v in dict(valid_before=validity(tb), valid_after=validity(ta),
                             cand_before=per_obs(tb, "generated"), cand_after=per_obs(ta, "generated"),
                             mrr_before=mrr(tb), mrr_after=mrr(ta), ms_before=ms(tb), ms_after=ms(ta),
                             gen_before=tb["generated"], valid_n_before=tb["valid"]).items():
                st[f"val/{kind}/{s}/{k}"] = round(v, 4)
        for s, _ in SIZES:
            st[f"validprefix/{kind}/{s}"] = [round(validity(A.get(kind, f"llmUnvalidated{s}", p)), 1) for p in PREF]
        for s in STRATEGIES:
            t = A.get(kind, s)
            st[f"ms/{kind}/{s}"] = round(ms(t), 1)
            st[f"memMB/{kind}/{s}"] = round(per_obs(t, "memoryBytes") / 1e6, 5)
    for kind in KINDS:
        for x, y in SIGN_PAIRS:
            w = l = t = 0
            for p in complete:
                a, b = A.pkg[(kind, x, p)], A.pkg[(kind, y, p)]
                if not a["count"]:
                    continue
                d = mrr(a) - mrr(b)
                if abs(d) < 1e-12:
                    t += 1
                elif d > 0:
                    w += 1
                else:
                    l += 1
            st[f"sign/{kind}/{x}>{y}"] = dict(win=w, loss=l, tie=t, p=sign_test(w, l))
    # Reranking keeps the candidate set: its Recall@10 equals Dependency's in every cell.
    cells = violations = 0
    for (p, k, s, pr), row in A.cell.items():
        if s.startswith("hybrid") and (p, k, DEP, pr) in A.cell:
            cells += 1
            violations += row["top10"] != A.cell[(p, k, DEP, pr)]["top10"]
    st["hybrid_invariant"] = dict(cells=cells, violations=violations)
    first = {}
    for part in parts:
        first.setdefault(part["package"], part["corpus"])
    total = lambda names: {f: sum(first[n][f] for n in names) for f in ("classes", "methods")}
    st["corpus_all"] = dict(packages=len(first), **total(first))
    st["corpus_matched"] = dict(packages=len(complete), **total(complete))
    st["tasks_done"] = len(parts)
    coverage = collections.Counter((p["kind"], p["strategy"]) for p in parts)
    st["coverage"] = {f"{k}/{s}": v for (k, s), v in sorted(coverage.items())}
    st["obs_matched"] = {k: A.get(k, DEP)["count"] for k in KINDS}
    st["obs_matched_by_prefix"] = {k: [A.get(k, DEP, p)["count"] for p in PREF] for k in KINDS}
    for kind in KINDS:
        r = coverage_rows(A, kind)
        for name, key in (("Cov (Dep)", "rec_d"), ("Cov (LM)", "rec_c"), ("T1 Dep", "t1_d"), ("T1 Hyb", "t1_r"),
                          ("T1 LM", "t1_c"), (r"T1$|$Cov Dep", "cond_d"), (r"T1$|$Cov Hyb", "cond_r")):
            st[f"hyb/{kind}/{name}"] = [round(v, 1) for v in r[key]]
    st["per_package_points"] = {f"{k}/{s}": len(package_points(A, k, s, complete))
                                for k in KINDS for s in ("llm7B", "hybrid7B")}
    legacy_names = {"D": "Dependency", "C": "LM", "R": "Hybrid",
                    r"$C_{\leq3}\!\to\!D$": r"LM$_{\le3}$ + Dependency", r"$C_{\leq3}\!\to\!R$": r"LM$_{\le3}$ + Hybrid"}
    for m in ("15B", "7B"):
        for i, (name, choose) in enumerate(POLICIES):
            if m == "7B" and i == 0:
                continue
            for kind in KINDS:
                v, share, t = policy(A, kind, choose, m)
                st[f"policy/{kind}/{m}/{legacy_names[name]}"] = dict(mrr=round(v, 4), invoke=round(share, 1), ms=round(t, 1))

    # Values quoted in the text that the original statistics file did not store.
    extra = {}
    extra["packages"] = complete
    extra["packages_with_observations"] = {k: sum(1 for p in complete if A.pkg[(k, DEP, p)]["count"]) for k in KINDS}
    extra["observations_total"] = sum(st["obs_matched"].values())
    for kind in KINDS:
        for s in ("hybrid7B", DEP):
            t = A.get(kind, s)
            extra[f"cond_top1_pooled/{kind}/{s}"] = ratio(t["top1"], t["top10"], 100)
            extra[f"top1_exact/{kind}/{s}"] = pct(t, "top1")
        # Observation counts must be identical across strategies in every package/prefix cell.
        extra[f"counts_match/{kind}"] = all(
            len({A.cell[(p, kind, s, pr)]["count"] for s in pipeline.MEASURED}) == 1
            for p in complete for pr in PREF)
    extra["ms_exact/messages/llm3B"] = ms(A.get("messages", "llm3B"))
    json_ready = {k: v for k, v in extra.items()}
    st["extra"] = json_ready
    return st


def without_nan(x):
    """Empty cells (NaN) as JSON null."""
    if isinstance(x, float) and math.isnan(x):
        return None
    if isinstance(x, dict):
        return {k: without_nan(v) for k, v in x.items()}
    if isinstance(x, list):
        return [without_nan(v) for v in x]
    return x


