# --------------------------------------------------------------------------- data
def load(checkpoints, workers):
    """Validated parts, the complete packages, and the ones still missing benchmarks."""
    manifest = json.loads(Path(workers).read_text())
    run_id, selected = manifest["runId"], manifest["packages"]
    parts = []
    for path in sorted(glob.glob(os.path.join(checkpoints, "*", "benchmarks", "*", "part.json"))):
        index = int(Path(path).parents[2].name) - 1
        package = selected[index]
        kind, strategy = Path(path).parent.name.split("-", 1)
        parts.append(pipeline.validate_part(Path(path), package, run_id, kind, strategy))
    by_package = collections.defaultdict(list)
    for part in parts:
        by_package[part["package"]].append(part)
    complete, incomplete = [], {}
    for package in selected:
        found = by_package.get(package, [])
        if not found:
            continue
        if len(found) == len(KINDS) * len(pipeline.MEASURED):
            if any(p["corpus"] != found[0]["corpus"] for p in found):
                raise ValueError(f"Benchmarks of {package} counted different corpora")
            complete.append(package)
        else:
            incomplete[package] = len(found)
    return manifest, parts, complete, incomplete


class Aggregates:
    """Observation-weighted sums over the complete packages."""

    def __init__(self, parts, complete):
        keep = set(complete)
        self.tot = collections.defaultdict(collections.Counter)   # (kind, s)
        self.pre = collections.defaultdict(collections.Counter)   # (kind, s, prefix)
        self.pkg = collections.defaultdict(collections.Counter)   # (kind, s, package)
        self.cell = {}                                             # (package, kind, s, prefix)
        for part in parts:
            for row in part["rows"]:
                self.cell[(part["package"], part["kind"], part["strategy"], row["prefix"])] = row
            if part["package"] not in keep:
                continue
            for row in part["rows"]:
                for f in FIELDS:
                    v = row.get(f, 0)
                    self.tot[(part["kind"], part["strategy"])][f] += v
                    self.pre[(part["kind"], part["strategy"], row["prefix"])][f] += v
                    self.pkg[(part["kind"], part["strategy"], part["package"])][f] += v

    def get(self, kind, s, prefix=None):
        return self.tot[(kind, s)] if prefix is None else self.pre[(kind, s, prefix)]


def ratio(num, den, scale=1):
    """scale * num / den; NaN for an empty cell (e.g. a run without class observations)."""
    return scale * num / den if den else math.nan


def mrr(a):
    return ratio(a["reciprocalRankSum"], a["count"])


def pct(a, field):
    return ratio(a[field], a["count"], 100)


def ms(a):
    return ratio(a["timeMs"], a["count"])


def per_obs(a, field):
    return ratio(a[field], a["count"])


def validity(a):
    return ratio(a["valid"], a["generated"], 100)


def sign_test(wins, losses):
    """Two-sided exact binomial sign test; ties are excluded."""
    n, k = wins + losses, min(wins, losses)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n) if n else 1.0


# --------------------------------------------------------------------------- formatting
# Empty cells (NaN) print as "--".
def f3(x):
    if math.isnan(x):
        return "--"
    text = f"{x:.3f}"
    return text[1:] if text.startswith("0.") else text


def f1(x):
    return "--" if math.isnan(x) else f"{x:.1f}"


def f2(x):
    return "--" if math.isnan(x) else f"{x:.2f}"


def thousands(x):
    if math.isnan(x):
        return "--"
    return f"{x:,.0f}".replace(",", "{,}")


def half_up(x):
    """Integer label: nearest integer, .5 rounded upward (the paper's rule)."""
    if math.isnan(x):
        return "--"
    return int(math.floor(x + 0.5))


def gain(v, ref):
    if math.isnan(v) or math.isnan(ref) or not ref:
        return ""
    return r"\textsuperscript{" + ("$+$" if v >= ref else "$-$") + f"{abs(100 * (v / ref - 1)):.1f}" + r"\%}"


def bold_best(columns):
    """Bold every cell equal to the column's best displayed value (ties included)."""
    out = []
    for column in columns:
        values = [float(t) for t in column if t != "--"]
        best = max(values, default=None)
        out.append([r"\textbf{" + t + "}" if t != "--" and float(t) == best else t for t in column])
    return out


BEST = r"\providecommand{\best}[1]{\cellcolor{green!14}\textbf{#1}}"
