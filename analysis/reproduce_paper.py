def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--checkpoints", default=str(ROOT / "data" / "checkpoints"),
                        help="packages/ directory of a benchmark run (default: the released checkpoints)")
    parser.add_argument("--workers", default=None,
                        help="the run's workers.json (default: data/provenance/workers.json, or ../workers.json next to --checkpoints)")
    parser.add_argument("--out", default=str(ROOT / "results"), help="output directory (default: results/)")
    args = parser.parse_args(argv)
    workers = args.workers
    if workers is None:
        sibling = Path(args.checkpoints).resolve().parent / "workers.json"
        workers = sibling if sibling.exists() else ROOT / "data" / "provenance" / "workers.json"

    manifest, parts, complete, incomplete = load(args.checkpoints, workers)
    if not complete:
        print("No package has all 28 benchmarks yet: nothing to analyse.", file=sys.stderr)
        return 1
    A = Aggregates(parts, complete)
    out = Path(args.out)
    (out / "paper").mkdir(parents=True, exist_ok=True)
    for name, build in OUTPUTS.items():
        (out / "paper" / name).write_text(build(A), encoding="utf-8")
    (out / "paper" / "fig-package-mrr.tex").write_text(fig_package_mrr(A, sorted(complete)), encoding="utf-8")
    st = statistics(A, parts, complete, incomplete, manifest)
    (out / "analysis-stats.json").write_text(json.dumps(without_nan(st), indent=1, allow_nan=False) + "\n", encoding="utf-8")
    print(f"Checkpoints: {len(parts)} validated benchmark parts")
    print(f"Analysed: {len(complete)} packages, "
          f"{st['obs_matched']['messages']:,} method and {st['obs_matched']['variables']:,} class observations per strategy")
    if incomplete:
        print("Skipped (not all 28 benchmarks yet): " + ", ".join(f"{p} ({n}/28)" for p, n in incomplete.items()))
    print(f"Wrote {len(OUTPUTS) + 1} paper files to {out / 'paper'} and {out / 'analysis-stats.json'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
