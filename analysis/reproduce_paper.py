def package_points(A, kind, s, packages, minimum=20):
    pts = []
    for p in packages:
        a, b = A.pkg[(kind, s, p)], A.pkg[(kind, DEP, p)]
        if a["count"] >= minimum:
            pts.append((mrr(b), mrr(a)))
    return pts


